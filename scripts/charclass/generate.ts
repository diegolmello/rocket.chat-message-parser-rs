import { readFileSync, writeFileSync } from 'node:fs';

const [grammarPath, outputPath] = process.argv.slice(2);
if (!grammarPath || !outputPath) {
	throw new Error('usage: bun scripts/charclass/generate.ts <grammar.pegjs> <output.rs>');
}

const grammar = readFileSync(grammarPath, 'utf8');

const classBody = (ruleName: string): string => {
	const match = grammar.match(new RegExp(`^${ruleName}\\s*=\\s*\\[([^\\n]*)\\]\\s*$`, 'm'));
	if (!match) {
		throw new Error(`rule ${ruleName} is not a single character class`);
	}
	return match[1];
};

const ranges = (body: string): Array<[number, number]> => {
	const pattern = new RegExp(`^[${body}]$`);
	const found: Array<[number, number]> = [];
	for (let unit = 0; unit <= 0xffff; unit++) {
		if (!pattern.test(String.fromCharCode(unit))) {
			continue;
		}
		const last = found[found.length - 1];
		if (last && last[1] === unit - 1) {
			last[1] = unit;
		} else {
			found.push([unit, unit]);
		}
	}
	return found;
};

const hex = (unit: number) => `0x${unit.toString(16).toUpperCase().padStart(4, '0')}`;

const table = (constName: string, ruleName: string) => {
	const rows = ranges(classBody(ruleName)).map(([low, high]) => `    (${hex(low)}, ${hex(high)}),`);
	return `pub const ${constName}: &[(u16, u16)] = &[\n${rows.join('\n')}\n];\n`;
};

const output = [
	'// Generated by scripts/charclass/generate.ts from grammar.pegjs; do not edit.\n',
	table('ALPHA_CHAR', 'AlphaChar'),
	table('DECIMAL_NUMBER_CHAR', 'DecimalNumberChar'),
	table('EMOJI_CHAR', 'EmojiChar'),
	table('MARK_CHAR', 'MarkChar'),
].join('\n');

writeFileSync(outputPath, output);
