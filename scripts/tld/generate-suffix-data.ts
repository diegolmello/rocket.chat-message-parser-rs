import { resolve } from "node:path";

type Trie = [0 | 1 | 2, { [label: string]: Trie }];

const [triePathArgument, outputPathArgument] = process.argv.slice(2);
if (!triePathArgument || !outputPathArgument) {
  console.error(
    "usage: bun scripts/tld/generate-suffix-data.ts <tldts>/src/data/trie.ts <output.rs>",
  );
  process.exit(1);
}

const { rules, exceptions } = (await import(resolve(triePathArgument))) as {
  rules: Trie;
  exceptions: Trie;
};

const compareUtf8 = (left: string, right: string) =>
  Buffer.compare(Buffer.from(left, "utf8"), Buffer.from(right, "utf8"));

const nodeIds = new Map<Trie, number>();
const nodeOrder: Trie[] = [];
const register = (root: Trie): number => {
  const queue: Trie[] = [root];
  if (!nodeIds.has(root)) {
    nodeIds.set(root, nodeOrder.length);
    nodeOrder.push(root);
  }
  while (queue.length > 0) {
    const node = queue.shift()!;
    for (const label of Object.keys(node[1]).sort(compareUtf8)) {
      const child = node[1][label]!;
      if (!nodeIds.has(child)) {
        nodeIds.set(child, nodeOrder.length);
        nodeOrder.push(child);
        queue.push(child);
      }
    }
  }
  return nodeIds.get(root)!;
};

const rulesRoot = register(rules);
const exceptionsRoot = register(exceptions);

const labelOffsets = new Map<string, number>();
let labelBytes = 0;
const labelLines: string[] = [];
let currentLine = "";
const internLabel = (label: string): number => {
  const known = labelOffsets.get(label);
  if (known !== undefined) {
    return known;
  }
  if (/["\\\s]/.test(label)) {
    throw new Error(`label needs escaping: ${JSON.stringify(label)}`);
  }
  const offset = labelBytes;
  labelOffsets.set(label, offset);
  labelBytes += Buffer.byteLength(label, "utf8");
  currentLine += label;
  if (currentLine.length >= 96) {
    labelLines.push(currentLine);
    currentLine = "";
  }
  return offset;
};

const nodeEntries: string[] = [];
const edgeEntries: string[] = [];
for (const node of nodeOrder) {
  const labels = Object.keys(node[1]).sort(compareUtf8);
  nodeEntries.push(`(${node[0]},${edgeEntries.length},${labels.length})`);
  for (const label of labels) {
    const length = Buffer.byteLength(label, "utf8");
    if (length > 255) {
      throw new Error(`label too long: ${label}`);
    }
    const reference = internLabel(label) * 256 + length;
    edgeEntries.push(`(${reference},${nodeIds.get(node[1][label]!)})`);
  }
}
if (currentLine) {
  labelLines.push(currentLine);
}

if (nodeEntries.length > 0xffff || edgeEntries.length > 0xffff || labelBytes >= 1 << 24) {
  throw new Error("suffix data no longer fits the packed integer widths");
}

const wrap = (entries: string[]) => {
  const lines: string[] = [];
  for (let index = 0; index < entries.length; index += 12) {
    lines.push(`    ${entries.slice(index, index + 12).join(",")},`);
  }
  return lines.join("\n");
};

const output = `// @generated by scripts/tld/generate-suffix-data.ts from tldts src/data/trie.ts; do not edit.

pub(super) const RULES_ROOT: u16 = ${rulesRoot};
pub(super) const EXCEPTIONS_ROOT: u16 = ${exceptionsRoot};

pub(super) static LABELS: &str = "\\
${labelLines.join("\\\n")}";

#[rustfmt::skip]
pub(super) static NODES: [(u8, u16, u16); ${nodeEntries.length}] = [
${wrap(nodeEntries)}
];

#[rustfmt::skip]
pub(super) static EDGES: [(u32, u16); ${edgeEntries.length}] = [
${wrap(edgeEntries)}
];
`;

await Bun.write(outputPathArgument, output);
console.log(
  `nodes=${nodeEntries.length} edges=${edgeEntries.length} label_bytes=${labelBytes}`,
);
