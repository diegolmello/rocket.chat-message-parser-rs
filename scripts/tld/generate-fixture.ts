const inputs = [
  ...new Set([...hosts.flatMap((host) => wrappers.map((wrap) => wrap(host))), ...standaloneInputs]),
];

const cases: unknown[] = [];
for (const [optionsName, options] of Object.entries(optionSets)) {
  const optionInputs =
    optionsName === "email"
      ? [...new Set([...inputs, ...inputs.map((input) => `mailto:${input}`)])]
      : inputs;
  for (const input of optionInputs) {
    const { hostname, domain, publicSuffix, isIcann, isPrivate, isIp } = parse(input, options);
    cases.push({ options: optionsName, input, hostname, domain, publicSuffix, isIcann, isPrivate, isIp });
  }
}

await Bun.write(
  outputPathArgument,
  [
    "{",
    `"tldtsVersion": ${JSON.stringify(version)},`,
    `"options": ${JSON.stringify(optionSets)},`,
    '"cases": [',
    cases.map((testCase) => JSON.stringify(testCase)).join(",\n"),
    "]",
    "}",
    "",
  ].join("\n"),
);
console.log(`inputs=${inputs.length} cases=${cases.length}`);
